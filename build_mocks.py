async def synth_line(persona, text, out_mp3):
    voice, pitch, rate = PERSONAS[persona]
    comm = edge_tts.Communicate(text, voice, pitch=pitch, rate=rate)
    await comm.save(out_mp3)

async def build_audio_clip(item):
    out_path = os.path.join(AUDIO_DIR, f"{item['id']}.mp3")
    if os.path.exists(out_path) and os.path.getsize(out_path) > 1000:
        return
    tmp = tempfile.mkdtemp()
    try:
        parts = []
        sil = os.path.join(tmp, "sil.mp3")
        subprocess.run(["ffmpeg", "-y", "-f", "lavfi", "-i", "anullsrc=r=24000:cl=mono", "-t", "0.4", "-q:a", "9", sil], capture_output=True)
        for idx, (pers, txt) in enumerate(item["turns"]):
            p_file = os.path.join(tmp, f"t{idx}.mp3")
            await synth_line(pers, txt, p_file)
            parts.append(p_file)
            if idx < len(item["turns"]) - 1:
                parts.append(sil)
        list_txt = os.path.join(tmp, "list.txt")
        with open(list_txt, "w") as f:
            for p in parts:
                f.write(f"file '{p}'\n")
        subprocess.run(["ffmpeg", "-y", "-f", "concat", "-safe", "0", "-i", list_txt, "-c:a", "libmp3lame", "-b:a", "48k", out_path], capture_output=True)
    finally:
        shutil.rmtree(tmp, ignore_errors=True)

async def generate_all_audio():
    sem = asyncio.Semaphore(4)
    async def run_one(it):
        async with sem:
            await build_audio_clip(it)
    await asyncio.gather(*(run_one(it) for it in SEC3_LISTEN_POOL))

def make_q(qid, prompt, jp, opts_cfirst, diff, cat, exp, svg=None, card=None, audio=None, transcript=None, opt_svgs=None):
    correct = opts_cfirst[0]
    if opt_svgs and len(opt_svgs) == len(opts_cfirst):
        paired = list(zip(opts_cfirst, opt_svgs))
        random.shuffle(paired)
        opts = [p[0] for p in paired]
        svgs_shuf = [p[1] for p in paired]
    else:
        opts = list(opts_cfirst)
        random.shuffle(opts)
        svgs_shuf = None
    ans = opts.index(correct)
    obj = {"id": qid, "prompt": prompt, "jp": jp, "opts": opts, "ans": ans, "diff": diff, "cat": cat, "exp": exp}
    if svg: obj["svg"] = svg
    if svgs_shuf: obj["optSvgs"] = svgs_shuf
    if card: obj["card"] = card
    if audio: obj["audio"] = audio
    if transcript: obj["transcript"] = transcript
    return obj

