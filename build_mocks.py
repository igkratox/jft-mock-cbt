# ---------------- GENERATE AUDIO CLIPS ----------------
async def synth_line(persona, text, out_mp3):
    voice, pitch, rate = PERSONAS[persona]
    comm = edge_tts.Communicate(text, voice, pitch=pitch, rate=rate)
    await comm.save(out_mp3)

async def build_audio_clip(item):
    out_path = os.path.join(AUDIO_DIR, f"{item['id']}.mp3")
    if os.path.exists(out_path) and os.path.getsize(out_path) > 1000:
        return
    tmp = tempfile.mkdtemp()
    try:
        parts = []
        sil = os.path.join(tmp, "sil.mp3")
        subprocess.run(["ffmpeg", "-y", "-f", "lavfi", "-i", "anullsrc=r=24000:cl=mono", "-t", "0.4", "-q:a", "9", sil], capture_output=True)
        for idx, (pers, txt) in enumerate(item["turns"]):
            p_file = os.path.join(tmp, f"t{idx}.mp3")
            await synth_line(pers, txt, p_file)
            parts.append(p_file)
            if idx < len(item["turns"]) - 1:
                parts.append(sil)
        list_txt = os.path.join(tmp, "list.txt")
        with open(list_txt, "w") as f:
            for p in parts:
                f.write(f"file '{p}'\n")
        subprocess.run(["ffmpeg", "-y", "-f", "concat", "-safe", "0", "-i", list_txt, "-c:a", "libmp3lame", "-b:a", "48k", out_path], capture_output=True)
    finally:
        shutil.rmtree(tmp, ignore_errors=True)

async def generate_all_audio():
    sem = asyncio.Semaphore(4)
    async def run_one(it):
        async with sem:
            await build_audio_clip(it)
    await asyncio.gather(*(run_one(it) for it in SEC3_LISTEN_POOL))

def make_q(qid, prompt, jp, opts_cfirst, diff, cat, exp, svg=None, card=None, audio=None, transcript=None, opt_svgs=None):
    correct = opts_cfirst[0]
    if opt_svgs and len(opt_svgs) == len(opts_cfirst):
        paired = list(zip(opts_cfirst, opt_svgs))
        random.shuffle(paired)
        opts = [p[0] for p in paired]
        svgs_shuf = [p[1] for p in paired]
    else:
        opts = list(opts_cfirst)
        random.shuffle(opts)
        svgs_shuf = None
    ans = opts.index(correct)
    obj = {"id": qid, "prompt": prompt, "jp": jp, "opts": opts, "ans": ans, "diff": diff, "cat": cat, "exp": exp}
    if svg: obj["svg"] = svg
    if svgs_shuf: obj["optSvgs"] = svgs_shuf
    if card: obj["card"] = card
    if audio: obj["audio"] = audio
    if transcript: obj["transcript"] = transcript
    return obj

# Section distribution patterns (48 to 52 Qs)
PATTERNS = [
    (12, 12, 12, 12), # 48
    (11, 13, 12, 12), # 48
    (13, 12, 12, 12), # 49
    (12, 13, 12, 13), # 50
    (13, 12, 13, 12), # 50
    (12, 14, 12, 13), # 51
    (14, 12, 13, 12), # 51
    (13, 13, 13, 13), # 52
    (12, 14, 12, 14), # 52
]

def build_mock(m_num):
    random.seed(202600 + m_num)
    c1, c2, c3, c4 = PATTERNS[(m_num - 1) % len(PATTERNS)]

    # Section 1: Script & Vocab (mix SVG + Kanji Read + Kanji Write + Usage)
    svgs = random.sample(SEC1_SVG, min(4, len(SEC1_SVG)))
    k_reads = random.sample(SEC1_KANJI_READ, min(4, len(SEC1_KANJI_READ)))
    k_writes = random.sample(SEC1_KANJI_WRITE, min(3, len(SEC1_KANJI_WRITE)))
    usages = random.sample(SEC1_USAGE, min(4, len(SEC1_USAGE)))
    s1_raw = []
    for p, j, o, d, ct, e, sv in svgs[:3]:
        s1_raw.append(make_q(f"m{m_num}_s1_{len(s1_raw)}", p, j, o, d, ct, e, svg=sv))
    for j, o, d, e in k_reads[:4]:
        s1_raw.append(make_q(f"m{m_num}_s1_{len(s1_raw)}", "How do you read the highlighted word?", j, o, d, "Kanji Reading", e))
    for j, o, d, e in k_writes[:3]:
        s1_raw.append(make_q(f"m{m_num}_s1_{len(s1_raw)}", "Choose the correct Kanji for the highlighted word.", j, o, d, "Kanji Usage", e))
    for j, o, d, e in usages:
        if len(s1_raw) < c1:
            s1_raw.append(make_q(f"m{m_num}_s1_{len(s1_raw)}", "Choose the best word to fill in the blank.", j, o, d, "Word Usage", e))
    while len(s1_raw) < c1:
        j, o, d, e = random.choice(SEC1_KANJI_READ)
        s1_raw.append(make_q(f"m{m_num}_s1_{len(s1_raw)}", "How do you read the highlighted word?", j, o, d, "Kanji Reading", e))
    s1_qs = s1_raw[:c1]

    # Section 2: Conversation & Expression
    g_pick = random.sample(SEC2_GRAMMAR, (c2 + 1) // 2)
    e_pick = random.sample(SEC2_EXPR, c2 - len(g_pick))
    s2_qs = []
    for j, o, d, e in g_pick:
        s2_qs.append(make_q(f"m{m_num}_s2_{len(s2_qs)}", "Choose the correct grammar to complete the sentence.", j, o, d, "Grammar", e))
    for j, o, d, e in e_pick:
        s2_qs.append(make_q(f"m{m_num}_s2_{len(s2_qs)}", "Choose the most appropriate expression.", j, o, d, "Expression", e))
    random.shuffle(s2_qs)

    # Section 3: Listening Comprehension (Multi-persona MP3, supports 1 or 2 Qs per audio)
    l_pool = list(SEC3_LISTEN_POOL)
    random.shuffle(l_pool)
    s3_qs = []
    for item in l_pool:
        if len(s3_qs) >= c3: break
        transcript = "\n".join(txt for _, txt in item["turns"])
        aud_url = f"audio/{item['id']}.mp3"
        for q_tup in item["qs"]:
            if len(s3_qs) >= c3: break
            pr, jp, o, d, e = q_tup[:5]
            osvgs = q_tup[5] if len(q_tup) > 5 else None
            s3_qs.append(make_q(f"m{m_num}_s3_{len(s3_qs)}", pr, jp, o, d, "Listening", e, audio=aud_url, transcript=transcript, opt_svgs=osvgs))

    # Section 4: Reading Comprehension (Email, SNS, Coupon, Poster)
    r_pool = list(SEC4_ITEMS)
    random.shuffle(r_pool)
    s4_qs = []
    for card, qlist in r_pool:
        if len(s4_qs) >= c4: break
        for pr, jp, o, d, e in qlist:
            if len(s4_qs) >= c4: break
            s4_qs.append(make_q(f"m{m_num}_s4_{len(s4_qs)}", pr, jp, o, d, "Reading", e, card=card))

    totalQ = len(s1_qs) + len(s2_qs) + len(s3_qs) + len(s4_qs)
    mid = f"m{m_num:02d}"
    mock_obj = {
        "id": mid,
        "title": f"JFT-Basic Mock Test #{m_num:02d}",
        "subtitle": f"Full 4-Section CBT · {totalQ} Questions (48–52 Format)",
        "totalQ": totalQ,
        "listenQ": len(s3_qs),
        "timeMin": 60,
        "sections": [
            {"name": "Script and Vocabulary", "timeMin": 15, "questions": s1_qs},
            {"name": "Conversation and Expression", "timeMin": 15, "questions": s2_qs},
            {"name": "Listening Comprehension", "timeMin": 15, "questions": s3_qs},
            {"name": "Reading Comprehension", "timeMin": 15, "questions": s4_qs},
        ]
    }
    with open(os.path.join(DATA_DIR, f"{mid}.json"), "w", encoding="utf-8") as f:
        json.dump(mock_obj, f, ensure_ascii=False)
    return {"id": mid, "title": mock_obj["title"], "subtitle": mock_obj["subtitle"], "totalQ": totalQ, "listenQ": len(s3_qs), "timeMin": 60}

